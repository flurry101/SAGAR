def generate_po_for_locale(locale: str, output_dir: str):
    os.makedirs(output_dir, exist_ok=True)
    po_path = os.path.join(output_dir, "messages.po")
    meta = LOCALES_METADATA.get(locale, {"name": locale, "native": locale})
    
    lines = [
        'msgid ""',
        'msgstr ""',
        f'"Language: {locale}\\n"',
        '"MIME-Version: 1.0\\n"',
        '"Content-Type: text/plain; charset=UTF-8\\n"',
        '"Content-Transfer-Encoding: 8bit\\n"',
        f'"X-Generator: SAGAR Marine i18n Engine (Coastal 22-Language Support)\\n"',
        f'"Language-Team: SAGAR {meta["name"]} ({meta["native"]})\\n"',
        "",
    ]
    
    for key, trans_map in TRANSLATIONS.items():
        source_text = trans_map.get("en", key)
        translated_text = trans_map.get(locale, source_text)
        
        lines.append(f'#: src/i18n/keys.ts:{key}')
        lines.append(f'msgid "{source_text}"')
        lines.append(f'msgstr "{translated_text}"')
        lines.append("")
    
    with open(po_path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    print(f"  [OK] Generated {po_path} ({meta['name']} - {meta['native']})")

def main():
    base_locales_dir = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "frontend", "src", "locales"))
    print(f"Generating 22-Language + English PO Catalogs into: {base_locales_dir}")
    
    for locale in LOCALES_METADATA.keys():
        locale_dir = os.path.join(base_locales_dir, locale)
        generate_po_for_locale(locale, locale_dir)
        
    print("\nSuccessfully generated all 23 language catalogs!")

if __name__ == "__main__":
    main()

